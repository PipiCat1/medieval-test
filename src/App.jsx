function applyEncounterEffects(baseTraits, effects) {
  const next = { ...baseTraits };
  Object.entries(effects?.traits || {}).forEach(([key, value]) => { next[key] = (next[key] || 0) + value; });
  return next;
}

function mergeFlags(flags, additions) {
  return Array.from(new Set([...flags, ...(additions || [])]));
}

function mergeInventory(items, additions) {
  return Array.from(new Set([...items, ...(additions || [])]));
}

function mergeNpcMemory(base, additions) {
  const next = { ...base };
  Object.entries(additions || {}).forEach(([key, value]) => { next[key] = (next[key] || 0) + value; });
  return next;
}

function getEncounterBundle(flags = []) {
  return flags.reduce((acc, flag) => {
    const extra = encounterExtras[flag];
    if (!extra) return acc;
    acc.items = mergeInventory(acc.items, extra.items);
    acc.npc = mergeNpcMemory(acc.npc, extra.npc);
    return acc;
  }, { items: [], npc: createInitialNpcMemory() });
}

function buildStory(answerIndexes, encounterNotes, primary, secondary) {
  const chosenAnswers = answerIndexes.map((answerIndex, qIndex) => questions[qIndex]?.answers?.[answerIndex]).filter(Boolean);
  const answerParts = chosenAnswers.map((item) => item.trail);
  const encounterParts = (encounterNotes || []).filter(Boolean);
  return {
    beginning: answerParts.slice(0, 3).join(' '),
    middle: encounterParts.slice(0, 5).join(' '),
    ending: answerParts.slice(3).join(' '),
    summary: `Твоя профессия — «${resultsMeta[primary]?.title || ''}». Ещё один подходящий вариант — «${resultsMeta[secondary]?.title || ''}».`,
  };
}

function getTopTraits(traits) {
  return Object.entries(traits).sort((a, b) => b[1] - a[1]).filter(([, value]) => value > 0)
    .slice(0, 4).map(([key, value]) => ({ key, value, label: traitLabels[key] || key }));
}

function getSpecialResult(primary, secondary, traits, flags) {
  const has = (flag) => flags.includes(flag);
  const minstrelSignals = [
    'dramaticContest', 'startedRumors', 'performedWit', 'performedMystery',
    'performedContractually', 'gentleJoke', 'sharpJoke', 'deadpanChaos',
    'setWarmTone', 'setLoudTone', 'setLegendaryTone', 'closedNightBeautifully',
    'closedNightFunny', 'closedNightMysteriously', 'playedHero', 'playedVillain',
    'playedMystery', 'tookLute',
  ].filter(has).length;
  if ((primary === 'scribe' || secondary === 'scribe') && has('insultedMonk')) return 'cursed_weirdo';
  if (primary === 'healer' && (traits.mercy >= 5 || (traits.piety >= 2 && traits.calm >= 2))) return 'blessed_remedy';
  if (((primary === 'minstrel' && minstrelSignals >= 3) || (secondary === 'minstrel' && minstrelSignals >= 4)) && (traits.charm >= 6 || (traits.charm >= 4 && traits.chaos >= 4))) return 'tavern_legend';
  if ((primary === 'steward' || secondary === 'steward') && traits.strategy >= 4 && (traits.charm >= 2 || traits.greed >= 2)) return 'velvet_conspirator';
  if ((primary === 'armorer' || secondary === 'armorer') && traits.practicality >= 4) return 'forge_gremlin';
  if ((primary === 'falconer' || primary === 'cartographer' || secondary === 'cartographer') && (traits.curiosity >= 3 || traits.weirdness >= 3)) return 'sky_omen';
  return null;
}

