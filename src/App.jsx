// Rebuild from the same adaptive choices the player actually saw.
// The fourth, added choice must count when revisiting earlier questions.
function rebuildProgress(answerIndexes, encounterChoices, lastIncludedIndex) {
  let traits = createInitialTraits();
  let npcMemory = createInitialNpcMemory();
  let inventory = [];
  let flags = [];
  for (let i = 0; i <= lastIncludedIndex; i += 1) {
    const encounter = getAdaptiveEncounter(i, answerIndexes[i], flags, inventory, npcMemory);
    const choice = encounter?.choices?.[encounterChoices[i]];
    if (!choice?.effects) continue;
    traits = applyEncounterEffects(traits, choice.effects);
    flags = mergeFlags(flags, choice.effects.flags);
    const bundle = getEncounterBundle(choice.effects.flags || []);
    inventory = mergeInventory(inventory, bundle.items);
    npcMemory = mergeNpcMemory(npcMemory, bundle.npc);
  }
  return { traits, npcMemory, inventory, flags };
}

